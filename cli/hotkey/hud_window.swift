    /// Present the Dynamic Island with Apple-grade "Drip" spring entrance animation.
    ///
    /// Idempotent: if the HUD is already visible (or mid-dismiss), this cancels any
    /// in-flight dismiss animation, snaps alphaValue back to 1 immediately, and
    /// bumps `generation` so that dismiss's own completion handler (scheduled
    /// before this call) sees a stale generation and never fires its cleanup —
    /// no stale hide can land on top of this newer show.
    public func show(state: HUDState = .listening) {
        ensureMainThread {
            self.generation += 1
            let myGen = self.generation

            if self.isHoverPeekActive {
                self.hideHoverPeek()
            }

            let notchInfo = NotchManager.shared.currentNotch()
            let targetH = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
            let targetW = HUDCapsuleView.capsuleWidth

            self.currentState = state
            self.transcribedText = nil
            self.isErrorEnvelope = false
            self.isSleepEnvelope = false
            self.currentWidth = targetW
            self.currentHeight = targetH

            self.panel.capsuleView.reset()
            self.panel.capsuleView.update(state: state)

            let finalFrame = self.computeFrame(width: targetW, height: targetH)

            let wasHidden = (self.lifecycle == .hidden)

            if wasHidden {
                self.lifecycle = .presenting

                if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                    // Reduce Motion: zero spatial travel, time preserved (80ms crossfade).
                    self.panel.setFrame(finalFrame, display: false)
                    self.panel.capsuleView.layer?.opacity = 1.0
                    self.panel.alphaValue = 0.0
                    self.orderFrontUnlessHeadless()

                    NSAnimationContext.runAnimationGroup({ context in
                        context.duration = HUDMotionTokens.reduceMotionDuration
                        context.timingFunction = CAMediaTimingFunction(name: .easeOut)
                        self.panel.animator().alphaValue = 1.0
                        self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: targetH)
                    }, completionHandler: {
                        guard myGen == self.generation else { return }
                        self.lifecycle = .visible
                    })
                } else {
                    // "The Drip": the notch unfolds downward under the real spring.
                    let startH = notchInfo.hasNotch ? notchInfo.notchHeight : targetH
                    self.panel.setFrame(self.computeFrame(width: targetW, height: startH), display: false)
                    self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: startH)
                    self.panel.alphaValue = 1.0
                    self.orderFrontUnlessHeadless()

                    self.springGeometry(
                        fromWidth: targetW, fromHeight: startH,
                        toWidth: targetW, toHeight: targetH,
                        fade: .fadeIn
                    ) {
                        guard myGen == self.generation else { return }
                        self.lifecycle = .visible
                    }
                }
                self.panel.invalidateShadow()
            } else {
                // Already presenting/visible/dismissing: idempotent re-show. Cancel any
                // in-flight dismiss fade by snapping alpha back to 1 directly (not via
                // .animator(), which would just queue behind the running animation).
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.lifecycle = .visible
                self.panel.capsuleView.layer?.removeAnimation(forKey: "hudSpringFade")
                self.panel.capsuleView.layer?.opacity = 1.0
                self.panel.alphaValue = 1.0
                self.orderFrontUnlessHeadless()
                self.panel.setFrame(finalFrame, display: true)
                self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: targetH)
                self.panel.invalidateShadow()
            }
        }
    }

    /// Expand Dynamic Island outward for dictation with dynamic multi-line height expansion (52px -> 76px -> 96px -> 110px).
    public func showTranscribedText(_ text: String) {
        ensureMainThread {
            self.transcribedText = text
            let targetH = self.panel.capsuleView.setTranscribedText(text)
            let targetW = HUDCapsuleView.expandedWidth

            self.resizeIsland(toWidth: targetW, height: targetH, animated: true)

            if !self.isVisible {
                self.show(state: .thinking)
                _ = self.panel.capsuleView.setTranscribedText(text)
                self.resizeIsland(toWidth: targetW, height: targetH, animated: false)
            }
        }
    }

    /// Render a high-level Semantic Action Breadcrumb (e.g. [Thinking], [Running], [Editing], [Searching], [Speaking]).
    public func showBreadcrumb(
        badge: String,
        detail: String,
        state: HUDState = .thinking,
        accentColor: NSColor? = nil
    ) {
        ensureMainThread {
            self.currentState = state
            self.panel.capsuleView.indicatorView.configure(for: state)
            let color = accentColor ?? state.accentColor
            let targetH = self.panel.capsuleView.setBreadcrumb(badge: badge, detail: detail, accentColor: color)
            let targetW = HUDCapsuleView.expandedWidth

            self.isSleepEnvelope = (badge.uppercased() == "PAUSED")
            self.panel.capsuleView.archieGlyph.state = HUDCapsuleView.archieGlyphState(for: state, badge: badge)
            // Sentence-arrival hook: main.swift emits one "Speaking" breadcrumb per spoken sentence
            // (word-level timing is not delivered to the HUD today) — one beat per sentence, not per word.
            if state == .speaking {
                self.panel.capsuleView.archieGlyph.beat()
            }

            self.resizeIsland(toWidth: targetW, height: targetH, animated: true)

            if !self.isVisible {
                self.show(state: state)
                _ = self.panel.capsuleView.setBreadcrumb(badge: badge, detail: detail, accentColor: color)
                self.resizeIsland(toWidth: targetW, height: targetH, animated: false)
            }
        }
    }

    /// Update HUD state dynamically (e.g. listening -> thinking -> speaking).
    public func update(state: HUDState) {
        ensureMainThread {
            self.currentState = state
            let notchInfo = NotchManager.shared.currentNotch()

            if let text = self.transcribedText, !text.isEmpty {
                self.panel.capsuleView.indicatorView.configure(for: state)
                let targetH = self.panel.capsuleView.setTranscribedText(text)
                self.resizeIsland(toWidth: HUDCapsuleView.expandedWidth, height: targetH, animated: false)
            } else {
                self.panel.capsuleView.update(state: state)
                let targetH = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
                self.resizeIsland(toWidth: HUDCapsuleView.capsuleWidth, height: targetH, animated: true)
            }
            if !self.isVisible {
                self.show(state: state)
            }
        }
    }

    /// Fluidly morph island width and height with Apple-grade spring physics.
    public func resizeIsland(toWidth newWidth: CGFloat, height newHeight: CGFloat, animated: Bool = true) {
        guard self.currentWidth != newWidth || self.currentHeight != newHeight else { return }
        self.currentWidth = newWidth
        self.currentHeight = newHeight

        let newFrame = computeFrame(width: newWidth, height: newHeight)

        if animated {
            if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                // Zero travel: snap to the new pose, no intermediate geometry.
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.panel.setFrame(newFrame, display: true)
                self.panel.capsuleView.layoutSubviews(forWidth: newWidth, height: newHeight)
            } else {
                // "The Blossom": width and height morph under the same spring.
                self.springGeometry(
                    fromWidth: self.panel.frame.width, fromHeight: self.panel.frame.height,
                    toWidth: newWidth, toHeight: newHeight
                )
            }
        } else {
            self.frameSpring?.cancel()
            self.frameSpring = nil
            self.panel.setFrame(newFrame, display: true)
            self.panel.capsuleView.layoutSubviews(forWidth: newWidth, height: newHeight)
        }
        self.panel.invalidateShadow()
    }

    /// Dismiss the HUD with a snappy suction retraction back into the physical notch.
    ///
    /// Captures the current `generation` before scheduling any animation. If a
    /// newer show() runs before this dismiss's animation completes, show() bumps
    /// `generation` — so this dismiss's `cleanup` sees a stale generation and
    /// becomes a no-op instead of hiding the panel out from under the newer show.
    /// `hardCut: true` is the barge/Escape path: an instant stop with zero
    /// animation. Anything else retracts under the spring.
    public func dismiss(hardCut: Bool = false, completion: (() -> Void)? = nil) {
        ensureMainThread {
            guard self.isVisible else {
                completion?()
                return
            }

            self.generation += 1
            let myGen = self.generation
            self.lifecycle = .dismissing

            let cleanup: () -> Void = {
                guard myGen == self.generation else {
                    // Superseded by a newer show()/dismiss() — do not touch state
                    // or hide a panel that a later call already took ownership of.
                    completion?()
                    return
                }
                self.panel.orderOut(nil)
                self.lifecycle = .hidden
                self.currentState = nil
                self.transcribedText = nil
                self.isErrorEnvelope = false
                self.isSleepEnvelope = false
                let notchInfo = NotchManager.shared.currentNotch()
                self.currentWidth = HUDCapsuleView.capsuleWidth
                self.currentHeight = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
                self.panel.capsuleView.reset()
                completion?()
            }

            if hardCut {
                // HARD CUT: a barge is a stop, not a transition. No spring, no
                // fade, no animation of any kind — the panel is gone on this turn
                // of the run loop, inside the 50ms budget by construction.
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.panel.capsuleView.layer?.removeAllAnimations()
                self.panel.capsuleView.layer?.opacity = 1.0
                self.panel.alphaValue = 1.0
                cleanup()
                return
            }

            if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                // Zero travel, time kept: an 80ms crossfade in place.
                NSAnimationContext.runAnimationGroup({ context in
                    context.duration = HUDMotionTokens.reduceMotionDuration
                    self.panel.animator().alphaValue = 0.0
                }, completionHandler: {
                    cleanup()
                })
                return
            }

            let notchInfo = NotchManager.shared.currentNotch()
            // "Suction": springs back up into the physical notch as it fades.
            let retractH = notchInfo.hasNotch ? notchInfo.notchHeight : self.currentHeight
            self.springGeometry(
                fromWidth: self.panel.frame.width, fromHeight: self.panel.frame.height,
                toWidth: HUDCapsuleView.capsuleWidth, toHeight: retractH,
                fade: .fadeOut
            ) {
                cleanup()
            }
        }
    }

    /// Compute frame based on active screen notch geometry:
    /// - If hardware notch exists: anchors flush to screen.frame.maxY, centered on the notch.
    /// - If no notch: centers horizontally on visibleFrame and floats 12px below menu bar.
    public func computeFrame(width: CGFloat, height: CGFloat) -> NSRect {
        let screen = NSScreen.main ?? (NSScreen.screens.first ?? NSScreen())
        let notchInfo = NotchManager.shared.currentNotch(for: screen)

        if notchInfo.hasNotch {
            let x = notchInfo.rect.midX - (width / 2.0)
            let y = notchInfo.screenFrame.maxY - height
            return NSRect(x: x, y: y, width: width, height: height)
        } else {
            let x = notchInfo.visibleFrame.midX - (width / 2.0)
            let y = notchInfo.visibleFrame.maxY - height - 12.0
            return NSRect(x: x, y: y, width: width, height: height)
        }
    }

    private func ensureMainThread(_ block: @escaping () -> Void) {
        if Thread.isMainThread {
            block()
        } else {
            DispatchQueue.main.async(execute: block)
        }
    }

