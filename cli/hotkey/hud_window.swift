// MARK: - HUDTokens
//
// The live spring/geometry/gesture values the HUD runs on. Two layers, no third:
//
//   1. DEFAULTS come from cli/hotkey/DesignTokens.swift — generated by
//      design/build.py from design/tokens.pet-talk.json (the design lane owns
//      both). No number below is typed twice; where DesignTokens has no
//      equivalent (the ear-fillet threshold, the pill radius, the double-tap
//      window) the value is pet-talk's own and lives here.
//   2. OVERRIDES come from ~/.pet-talk/config.yaml (`motion:` / `geometry:` /
//      `hotkey:`, see config.swift), applied at launch by HUDTokens.apply(from:),
//      so a design-playground export lands without a rebuild.
//
// Everything is a `static var` for exactly that reason.
public struct HUDTokens {
    // Damped-spring physics. These three are the ONLY source of spring numbers:
    // HUDSpring.animation() and HUDSpringDriver both read them.
    public static var springStiffness: Double = DesignTokens.springStiffness
    public static var springDamping: Double = DesignTokens.springDamping
    public static var springMass: Double = DesignTokens.springMass

    // Geometry. capsuleWidth itself is measured from the screen, never stored.
    public static var fallbackCapsuleWidth: CGFloat = CGFloat(DesignTokens.capsuleWidthRest)
    public static var expandedWidth: CGFloat = CGFloat(DesignTokens.capsuleWidthExpanded)
    /// pet-talk's own: how far content must spill past the notch before ears appear.
    public static var earFilletThreshold: CGFloat = 24.0
    public static var earFilletRadius: CGFloat = CGFloat(DesignTokens.radiusEarFillet)
    public static var bottomCornerRadius: CGFloat = CGFloat(DesignTokens.radiusBottom)
    /// pet-talk's own: the no-notch floating pill is rounder than the island.
    public static var pillCornerRadius: CGFloat = 22.0

    // Gesture (pet-talk's own: the pause window)
    public static var doubleTapWindowMs: Double = 400.0

    /// Apply a config.yaml override. Unset keys keep the built-in default.
    public static func apply(from config: PetTalkConfig) {
        if let v = config.motion.springStiffness { springStiffness = v }
        if let v = config.motion.springDamping { springDamping = v }
        if let v = config.motion.springMass { springMass = v }
        if let v = config.geometry.notchWidthFallback { fallbackCapsuleWidth = v }
        if let v = config.geometry.expandedWidth { expandedWidth = v }
        if let v = config.geometry.earFilletThreshold { earFilletThreshold = v }
        if let v = config.geometry.earFilletRadius { earFilletRadius = v }
        if let v = config.geometry.bottomCornerRadius { bottomCornerRadius = v }
        if let v = config.geometry.pillCornerRadius { pillCornerRadius = v }
        if let v = config.hotkey.doubleTapWindowMs { doubleTapWindowMs = v }
    }
}

// MARK: - Spring: the one CASpringAnimation factory

public enum HUDSpring {
    /// The single place a CASpringAnimation is constructed. Its physics read the
    /// three declared tokens; a literal here would be the bug this replaced.
    public static func animation(keyPath: String, from: Any?, to: Any?) -> CASpringAnimation {
        let spring = CASpringAnimation(keyPath: keyPath)
        spring.mass = CGFloat(HUDTokens.springMass)
        spring.stiffness = CGFloat(HUDTokens.springStiffness)
        spring.damping = CGFloat(HUDTokens.springDamping)
        spring.initialVelocity = 0.0
        spring.fromValue = from
        spring.toValue = to
        spring.duration = spring.settlingDuration
        spring.fillMode = .both
        spring.isRemovedOnCompletion = true
        return spring
    }

    /// Settling time of the declared spring, in seconds.
    public static var settlingDuration: Double {
        Double(animation(keyPath: "opacity", from: 0.0, to: 1.0).settlingDuration)
    }
}

// MARK: - Spring driver (window frame)

/// A CASpringAnimation cannot drive an NSWindow's frame, and the HUD *is* a
/// window — so window geometry is integrated here from the SAME three tokens:
/// semi-implicit Euler on a = (-k*x - c*v) / m, stepped at 120 Hz, reporting a
/// normalized 0 -> 1 progress (overshoot included) that the caller lerps its
/// geometry along.
public final class HUDSpringDriver {
    private let stiffness: Double
    private let damping: Double
    private let mass: Double
    private let onStep: (Double) -> Void
    private let onDone: () -> Void
    private let stepSeconds: Double = 1.0 / 120.0
    private let timeoutSeconds: Double

    private var position: Double = 0.0
    private var velocity: Double = 0.0
    private var elapsed: Double = 0.0
    private var timer: Timer?

    public init(
        stiffness: Double = HUDTokens.springStiffness,
        damping: Double = HUDTokens.springDamping,
        mass: Double = HUDTokens.springMass,
        timeoutSeconds: Double = 1.5,
        onStep: @escaping (Double) -> Void,
        onDone: @escaping () -> Void
    ) {
        self.stiffness = stiffness
        self.damping = damping
        self.mass = mass
        self.timeoutSeconds = timeoutSeconds
        self.onStep = onStep
        self.onDone = onDone
    }

    public var isRunning: Bool { timer != nil }

    public func start() {
        cancel()
        position = 0.0
        velocity = 0.0
        elapsed = 0.0
        onStep(0.0)
        let t = Timer(timeInterval: stepSeconds, repeats: true) { [weak self] _ in
            self?.tick()
        }
        timer = t
        // .common so the spring keeps stepping while a menu or drag tracks.
        RunLoop.main.add(t, forMode: .common)
    }

    private func tick() {
        elapsed += stepSeconds
        let displacement = position - 1.0
        let acceleration = (-stiffness * displacement - damping * velocity) / max(0.0001, mass)
        velocity += acceleration * stepSeconds
        position += velocity * stepSeconds

        // Sub-pixel: 0.004 of a 14pt travel is 0.06pt, so the tail below this is
        // invisible and holding the timer open for it only burns CPU.
        let settled = abs(position - 1.0) < 0.004 && abs(velocity) < 0.05
        if settled || elapsed >= timeoutSeconds {
            position = 1.0
            velocity = 0.0
            onStep(1.0)
            cancel()
            onDone()
            return
        }
        onStep(max(0.0, position))
    }

    public func cancel() {
        timer?.invalidate()
        timer = nil
    }
}

