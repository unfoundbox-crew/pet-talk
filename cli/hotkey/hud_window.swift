// MARK: - HUDController Singleton

/// Single-state lifecycle for the HUD panel. Replaces the old boolean `isVisible`
/// plus ad-hoc animation bookkeeping so show()/dismiss() can never race each other:
/// each transition bumps `generation`, and any completion handler scheduled by a
/// prior transition checks its captured generation before mutating state — a
/// stale dismiss cleanup from before a newer show() is a no-op.
public enum HUDLifecycle {
    case hidden
    case presenting
    case visible
    case dismissing
}

public class HUDController {
    public static let shared = HUDController()

    public let panel = HUDPanel()
    public private(set) var currentState: HUDState?
    public private(set) var currentWidth: CGFloat = HUDCapsuleView.capsuleWidth
    public private(set) var currentHeight: CGFloat = HUDCapsuleView.notchListeningHeight
    public private(set) var transcribedText: String?
    public private(set) var lifecycle: HUDLifecycle = .hidden
    public var isVisible: Bool { lifecycle == .presenting || lifecycle == .visible || lifecycle == .dismissing }
    public private(set) var isHoverPeekActive: Bool = false

    /// The capsule is showing a failure and waiting to be dismissed. Set by the
    /// error path, cleared on the next show/dismiss — the error envelope is the
    /// only one that does not retract on its own.
    public private(set) var isErrorEnvelope: Bool = false
    /// Paused (sleep mode). Set from a "PAUSED" breadcrumb.
    public private(set) var isSleepEnvelope: Bool = false

    /// Which of the six envelopes the capsule is wearing right now. Derived, never
    /// stored twice: the envelope is a consequence of state plus measured
    /// geometry, so it cannot disagree with what is on screen.
    public var currentEnvelope: HUDEnvelope {
        let notchInfo = NotchManager.shared.currentNotch()
        guard notchInfo.hasNotch else { return .pill }
        if isErrorEnvelope { return .error }
        if isSleepEnvelope { return .sleep }
        if currentHeight > HUDCapsuleView.notchExpandedHeight + 1.0 { return .tall }
        if currentWidth > HUDCapsuleView.capsuleWidth + 40.0 { return .expanded }
        return .compact
    }

    /// Bumped on every show()/dismiss() call. A completion handler captures the
    /// generation at schedule time and only applies its cleanup if it is still
    /// current — this is what makes a stale dismiss never clobber a newer show.
    private var generation: Int = 0

    // Sensory & Execution Callbacks
    public var onBargeKill: (() -> Void)?
    public var onErrorAudio: (() -> Void)?
    public var onTriggerTurn: (() -> Void)?

    private var localKeyMonitor: Any?
    private var globalMouseMonitor: Any?

    /// The in-flight geometry spring, if any. Cancelled by any newer transition
    /// and by the barge hard cut.
    private var frameSpring: HUDSpringDriver?

    /// PET_TALK_HEADLESS=1 runs every state transition, spring step and geometry
    /// computation as usual but never puts a panel on screen. The QA suites set
    /// it, so a test can never pop the capsule onto the screen someone is working
    /// on (Saurabh, 2026-09-12).
    public static var isHeadless: Bool {
        let raw = (ProcessInfo.processInfo.environment["PET_TALK_HEADLESS"] ?? "").lowercased()
        return raw == "1" || raw == "true" || raw == "yes"
    }

    /// Every path that would show the panel goes through here.
    private func orderFrontUnlessHeadless() {
        guard !HUDController.isHeadless else { return }
        panel.orderFrontRegardless()
    }

    private init() {}

    private enum SpringFade {
        case none
        case fadeIn
        case fadeOut
    }

    /// Drive the panel from one pose to another under the declared damped spring.
    /// Frame geometry is integrated by HUDSpringDriver (a window frame is not
    /// animatable by Core Animation); the capsule's opacity rides a real
    /// CASpringAnimation. Both read the same three tokens, so they settle together.
    private func springGeometry(
        fromWidth: CGFloat,
        fromHeight: CGFloat,
        toWidth: CGFloat,
        toHeight: CGFloat,
        fade: SpringFade = .none,
        completion: (() -> Void)? = nil
    ) {
        frameSpring?.cancel()

        if fade != .none, let layer = panel.capsuleView.layer {
            let from: Float = (fade == .fadeIn) ? 0.0 : 1.0
            let to: Float = (fade == .fadeIn) ? 1.0 : 0.0
            layer.removeAnimation(forKey: "hudSpringFade")
            layer.add(HUDSpring.animation(keyPath: "opacity", from: from, to: to), forKey: "hudSpringFade")
            layer.opacity = to
        }

        let driver = HUDSpringDriver(onStep: { [weak self] progress in
            guard let self = self else { return }
            let p = CGFloat(progress)
            let w = max(1.0, fromWidth + (toWidth - fromWidth) * p)
            let h = max(1.0, fromHeight + (toHeight - fromHeight) * p)
            CATransaction.begin()
            CATransaction.setDisableActions(true)
            self.panel.setFrame(self.computeFrame(width: w, height: h), display: false)
            self.panel.capsuleView.layoutSubviews(forWidth: w, height: h)
            CATransaction.commit()
        }, onDone: { [weak self] in
            guard let self = self else { return }
            self.frameSpring = nil
            self.panel.invalidateShadow()
            completion?()
        })
        frameSpring = driver
        driver.start()
    }

    /// Register local Escape monitor and global notch hover tracking
    public func setupEventMonitors() {
        ensureMainThread {
            if self.localKeyMonitor == nil {
                self.localKeyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
                    guard let self = self else { return event }
                    // Escape key (keycode 53): instant <= 50ms dismiss and barge-kill
                    if event.keyCode == 53 && (self.isVisible || self.isHoverPeekActive) {
                        self.dismissWithBargeKill()
                        return nil
                    }
                    return event
                }
            }

            if self.globalMouseMonitor == nil {
                self.globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(matching: .mouseMoved) { [weak self] _ in
                    guard let self = self else { return }
                    let mouseLoc = NSEvent.mouseLocation
                    let notchInfo = NotchManager.shared.currentNotch()
                    guard notchInfo.hasNotch else { return }

                    let notchH = notchInfo.notchHeight
                    let notchW = HUDCapsuleView.capsuleWidth
                    let notchX = notchInfo.screenFrame.midX - (notchW / 2.0)
                    let notchY = notchInfo.screenFrame.maxY - notchH - HUDCapsuleView.hoverPeekHeight
                    let notchZone = NSRect(
                        x: notchX,
                        y: notchY,
                        width: notchW,
                        height: notchH + HUDCapsuleView.hoverPeekHeight + 4.0
                    )

                    if notchZone.contains(mouseLoc) {
                        if !self.isVisible && !self.isHoverPeekActive {
                            self.showHoverPeek()
                        }
                    } else {
                        if self.isHoverPeekActive {
                            self.hideHoverPeek()
                        }
                    }
                }
            }
        }
    }

    /// Hover peek: the capsule drops by the hoverPeek token and shows the sleep
    /// bead — enough to say "she is here" and nothing more.
    public func showHoverPeek() {
        ensureMainThread {
            guard !self.isVisible, !self.isHoverPeekActive else { return }
            let notchInfo = NotchManager.shared.currentNotch()
            guard notchInfo.hasNotch else { return }

            self.isHoverPeekActive = true
            let peekH = notchInfo.notchHeight + HUDCapsuleView.hoverPeekHeight
            let frame = self.computeFrame(width: HUDCapsuleView.capsuleWidth, height: peekH)

            self.panel.ignoresMouseEvents = false
            self.panel.setFrame(frame, display: true)
            self.panel.alphaValue = 1.0
            self.panel.capsuleView.sleepBeadLayer.opacity = 1.0
            self.panel.capsuleView.indicatorView.isHidden = true
            self.panel.capsuleView.labelField.stringValue = ""
            self.orderFrontUnlessHeadless()
        }
    }

    /// Snap hover peek back into the physical notch
    public func hideHoverPeek() {
        ensureMainThread {
            guard self.isHoverPeekActive else { return }
            self.isHoverPeekActive = false
            self.panel.ignoresMouseEvents = true
            self.panel.capsuleView.sleepBeadLayer.opacity = 0.0
            self.panel.capsuleView.indicatorView.isHidden = false
            self.panel.orderOut(nil)
        }
    }

