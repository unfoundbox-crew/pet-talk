// MARK: - HUDController Singleton

/// Single-state lifecycle for the HUD panel. Replaces the old boolean `isVisible`
/// plus ad-hoc animation bookkeeping so show()/dismiss() can never race each other:
/// each transition bumps `generation`, and any completion handler scheduled by a
/// prior transition checks its captured generation before mutating state — a
/// stale dismiss cleanup from before a newer show() is a no-op.
public enum HUDLifecycle {
    case hidden
    case presenting
    case visible
    case dismissing
}

public class HUDController {
    public static let shared = HUDController()

    public let panel = HUDPanel()
    public private(set) var currentState: HUDState?
    public private(set) var currentWidth: CGFloat = HUDCapsuleView.capsuleWidth
    public private(set) var currentHeight: CGFloat = HUDCapsuleView.notchListeningHeight
    public private(set) var transcribedText: String?
    public private(set) var lifecycle: HUDLifecycle = .hidden
    public var isVisible: Bool { lifecycle == .presenting || lifecycle == .visible || lifecycle == .dismissing }
    public private(set) var isHoverPeekActive: Bool = false

    /// Bumped on every show()/dismiss() call. A completion handler captures the
    /// generation at schedule time and only applies its cleanup if it is still
    /// current — this is what makes a stale dismiss never clobber a newer show.
    private var generation: Int = 0

    // Sensory & Execution Callbacks
    public var onBargeKill: (() -> Void)?
    public var onErrorAudio: (() -> Void)?
    public var onTriggerTurn: (() -> Void)?

    private var localKeyMonitor: Any?
    private var globalMouseMonitor: Any?

    /// The in-flight geometry spring, if any. Cancelled by any newer transition
    /// and by the barge hard cut.
    private var frameSpring: HUDSpringDriver?

    /// PET_TALK_HEADLESS=1 runs every state transition, spring step and geometry
    /// computation as usual but never puts a panel on screen. The QA suites set
    /// it, so a test can never pop the capsule onto the screen someone is working
    /// on (Saurabh, 2026-09-12).
    public static var isHeadless: Bool {
        let raw = (ProcessInfo.processInfo.environment["PET_TALK_HEADLESS"] ?? "").lowercased()
        return raw == "1" || raw == "true" || raw == "yes"
    }

    /// Every path that would show the panel goes through here.
    private func orderFrontUnlessHeadless() {
        guard !HUDController.isHeadless else { return }
        panel.orderFrontRegardless()
    }

    private init() {}

    private enum SpringFade {
        case none
        case fadeIn
        case fadeOut
    }

    /// Drive the panel from one pose to another under the declared damped spring.
    /// Frame geometry is integrated by HUDSpringDriver (a window frame is not
    /// animatable by Core Animation); the capsule's opacity rides a real
    /// CASpringAnimation. Both read the same three tokens, so they settle together.
    private func springGeometry(
        fromWidth: CGFloat,
        fromHeight: CGFloat,
        toWidth: CGFloat,
        toHeight: CGFloat,
        fade: SpringFade = .none,
        completion: (() -> Void)? = nil
    ) {
        frameSpring?.cancel()

        if fade != .none, let layer = panel.capsuleView.layer {
            let from: Float = (fade == .fadeIn) ? 0.0 : 1.0
            let to: Float = (fade == .fadeIn) ? 1.0 : 0.0
            layer.removeAnimation(forKey: "hudSpringFade")
            layer.add(HUDSpring.animation(keyPath: "opacity", from: from, to: to), forKey: "hudSpringFade")
            layer.opacity = to
        }

        let driver = HUDSpringDriver(onStep: { [weak self] progress in
            guard let self = self else { return }
            let p = CGFloat(progress)
            let w = max(1.0, fromWidth + (toWidth - fromWidth) * p)
            let h = max(1.0, fromHeight + (toHeight - fromHeight) * p)
            CATransaction.begin()
            CATransaction.setDisableActions(true)
            self.panel.setFrame(self.computeFrame(width: w, height: h), display: false)
            self.panel.capsuleView.layoutSubviews(forWidth: w, height: h)
            CATransaction.commit()
        }, onDone: { [weak self] in
            guard let self = self else { return }
            self.frameSpring = nil
            self.panel.invalidateShadow()
            completion?()
        })
        frameSpring = driver
        driver.start()
    }

    /// Register local Escape monitor and global notch hover tracking
    public func setupEventMonitors() {
        ensureMainThread {
            if self.localKeyMonitor == nil {
                self.localKeyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
                    guard let self = self else { return event }
                    // Escape key (keycode 53): instant <= 50ms dismiss and barge-kill
                    if event.keyCode == 53 && (self.isVisible || self.isHoverPeekActive) {
                        self.dismissWithBargeKill()
                        return nil
                    }
                    return event
                }
            }

            if self.globalMouseMonitor == nil {
                self.globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(matching: .mouseMoved) { [weak self] _ in
                    guard let self = self else { return }
                    let mouseLoc = NSEvent.mouseLocation
                    let notchInfo = NotchManager.shared.currentNotch()
                    guard notchInfo.hasNotch else { return }

                    let notchH = notchInfo.notchHeight
                    let notchW = HUDCapsuleView.capsuleWidth
                    let notchX = notchInfo.screenFrame.midX - (notchW / 2.0)
                    let notchY = notchInfo.screenFrame.maxY - notchH - HUDCapsuleView.hoverPeekHeight
                    let notchZone = NSRect(
                        x: notchX,
                        y: notchY,
                        width: notchW,
                        height: notchH + HUDCapsuleView.hoverPeekHeight + 4.0
                    )

                    if notchZone.contains(mouseLoc) {
                        if !self.isVisible && !self.isHoverPeekActive {
                            self.showHoverPeek()
                        }
                    } else {
                        if self.isHoverPeekActive {
                            self.hideHoverPeek()
                        }
                    }
                }
            }
        }
    }

    /// Subtle notch hover peek (6px downward expansion revealing SpacePilot Gold dot)
    public func showHoverPeek() {
        ensureMainThread {
            guard !self.isVisible, !self.isHoverPeekActive else { return }
            let notchInfo = NotchManager.shared.currentNotch()
            guard notchInfo.hasNotch else { return }

            self.isHoverPeekActive = true
            let peekH = notchInfo.notchHeight + HUDCapsuleView.hoverPeekHeight
            let frame = self.computeFrame(width: HUDCapsuleView.capsuleWidth, height: peekH)

            self.panel.ignoresMouseEvents = false
            self.panel.setFrame(frame, display: true)
            self.panel.alphaValue = 1.0
            self.panel.capsuleView.goldDotLayer.opacity = 1.0
            self.panel.capsuleView.indicatorView.isHidden = true
            self.panel.capsuleView.labelField.stringValue = ""
            self.orderFrontUnlessHeadless()
        }
    }

    /// Snap hover peek back into the physical notch
    public func hideHoverPeek() {
        ensureMainThread {
            guard self.isHoverPeekActive else { return }
            self.isHoverPeekActive = false
            self.panel.ignoresMouseEvents = true
            self.panel.capsuleView.goldDotLayer.opacity = 0.0
            self.panel.capsuleView.indicatorView.isHidden = false
            self.panel.orderOut(nil)
        }
    }

    public func handleMouseEntered() {
        showHoverPeek()
    }

    public func handleMouseExited() {
        hideHoverPeek()
    }

    public func handleCapsuleClick() {
        ensureMainThread {
            if self.isHoverPeekActive {
                self.hideHoverPeek()
                if let trigger = self.onTriggerTurn {
                    trigger()
                } else {
                    self.show(state: .listening)
                }
            }
        }
    }

    /// Instant Escape dismiss: terminates active speech/processes in <= 50ms
    public func dismissWithBargeKill() {
        ensureMainThread {
            self.onBargeKill?()
            if self.isHoverPeekActive {
                self.hideHoverPeek()
            }
            if self.isVisible {
                self.dismiss(hardCut: true)
            }
        }
    }

    /// 3-cycle horizontal micro-shake feedback (±3px over 120ms) + Basso chime
    public func triggerErrorShake(completion: (() -> Void)? = nil) {
        ensureMainThread {
            guard self.isVisible else {
                completion?()
                return
            }

            if let audio = self.onErrorAudio {
                audio()
            } else if !EarconEngine.isSilentModeEnv && !HUDController.isHeadless {
                NSSound(named: "Basso")?.play()
            }

            guard !NSWorkspace.shared.accessibilityDisplayShouldReduceMotion else {
                completion?()
                return
            }

            // N cycles of +/- amplitude, both read from tokens, decaying to rest.
            let amplitude = HUDMotionTokens.errorShakeAmplitude
            let cycles = max(1, HUDMotionTokens.errorShakeCycles)
            var values: [Double] = [0.0]
            for cycle in 0..<cycles {
                let decay = 1.0 - (Double(cycle) / Double(cycles)) * 0.35
                values.append(-amplitude * decay)
                values.append(amplitude * decay)
            }
            values.append(0.0)

            let shake = CAKeyframeAnimation(keyPath: "transform.translation.x")
            shake.duration = HUDMotionTokens.errorShakeDuration
            shake.values = values
            shake.timingFunction = CAMediaTimingFunction(name: .easeInEaseOut)
            shake.isRemovedOnCompletion = true
            self.panel.capsuleView.layer?.add(shake, forKey: "errorShake")

            DispatchQueue.main.asyncAfter(deadline: .now() + HUDMotionTokens.errorShakeDuration) {
                completion?()
            }
        }
    }

    /// Alias for triggerErrorShake
    public func shakeError(completion: (() -> Void)? = nil) {
        triggerErrorShake(completion: completion)
    }

    /// Real-time microphone acoustic energy levels (RMS / peak, normalized 0.0 ... 1.0)
    public func updateAudioLevel(rms: Float, peak: Float) {
        ensureMainThread {
            guard self.isVisible, self.currentState == .listening else { return }
            self.panel.capsuleView.updateAudioLevel(rms: rms, peak: peak)
        }
    }

    /// Present the Dynamic Island with Apple-grade "Drip" spring entrance animation.
    ///
    /// Idempotent: if the HUD is already visible (or mid-dismiss), this cancels any
    /// in-flight dismiss animation, snaps alphaValue back to 1 immediately, and
    /// bumps `generation` so that dismiss's own completion handler (scheduled
    /// before this call) sees a stale generation and never fires its cleanup —
    /// no stale hide can land on top of this newer show.
    public func show(state: HUDState = .listening) {
        ensureMainThread {
            self.generation += 1
            let myGen = self.generation

            if self.isHoverPeekActive {
                self.hideHoverPeek()
            }

            let notchInfo = NotchManager.shared.currentNotch()
            let targetH = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
            let targetW = HUDCapsuleView.capsuleWidth

            self.currentState = state
            self.transcribedText = nil
            self.currentWidth = targetW
            self.currentHeight = targetH

            self.panel.capsuleView.reset()
            self.panel.capsuleView.update(state: state)

            let finalFrame = self.computeFrame(width: targetW, height: targetH)

            let wasHidden = (self.lifecycle == .hidden)

            if wasHidden {
                self.lifecycle = .presenting

                if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                    // Reduce Motion: zero spatial travel, time preserved (80ms crossfade).
                    self.panel.setFrame(finalFrame, display: false)
                    self.panel.capsuleView.layer?.opacity = 1.0
                    self.panel.alphaValue = 0.0
                    self.orderFrontUnlessHeadless()

                    NSAnimationContext.runAnimationGroup({ context in
                        context.duration = HUDMotionTokens.reduceMotionDuration
                        context.timingFunction = CAMediaTimingFunction(name: .easeOut)
                        self.panel.animator().alphaValue = 1.0
                        self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: targetH)
                    }, completionHandler: {
                        guard myGen == self.generation else { return }
                        self.lifecycle = .visible
                    })
                } else {
                    // "The Drip": the notch unfolds downward under the real spring.
                    let startH = notchInfo.hasNotch ? notchInfo.notchHeight : targetH
                    self.panel.setFrame(self.computeFrame(width: targetW, height: startH), display: false)
                    self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: startH)
                    self.panel.alphaValue = 1.0
                    self.orderFrontUnlessHeadless()

                    self.springGeometry(
                        fromWidth: targetW, fromHeight: startH,
                        toWidth: targetW, toHeight: targetH,
                        fade: .fadeIn
                    ) {
                        guard myGen == self.generation else { return }
                        self.lifecycle = .visible
                    }
                }
                self.panel.invalidateShadow()
            } else {
                // Already presenting/visible/dismissing: idempotent re-show. Cancel any
                // in-flight dismiss fade by snapping alpha back to 1 directly (not via
                // .animator(), which would just queue behind the running animation).
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.lifecycle = .visible
                self.panel.capsuleView.layer?.removeAnimation(forKey: "hudSpringFade")
                self.panel.capsuleView.layer?.opacity = 1.0
                self.panel.alphaValue = 1.0
                self.orderFrontUnlessHeadless()
                self.panel.setFrame(finalFrame, display: true)
                self.panel.capsuleView.layoutSubviews(forWidth: targetW, height: targetH)
                self.panel.invalidateShadow()
            }
        }
    }

    /// Expand Dynamic Island outward for dictation with dynamic multi-line height expansion (52px -> 76px -> 96px -> 110px).
    public func showTranscribedText(_ text: String, persona: String = "Donna") {
        ensureMainThread {
            self.transcribedText = text
            let targetH = self.panel.capsuleView.setTranscribedText(text, persona: persona)
            let targetW = HUDCapsuleView.expandedWidth

            self.resizeIsland(toWidth: targetW, height: targetH, animated: true)

            if !self.isVisible {
                self.show(state: .thinking)
                _ = self.panel.capsuleView.setTranscribedText(text, persona: persona)
                self.resizeIsland(toWidth: targetW, height: targetH, animated: false)
            }
        }
    }

    /// Render a high-level Semantic Action Breadcrumb (e.g. [Thinking], [Running], [Editing], [Searching], [Speaking]).
    public func showBreadcrumb(
        badge: String,
        detail: String,
        state: HUDState = .thinking,
        accentColor: NSColor? = nil
    ) {
        ensureMainThread {
            self.currentState = state
            self.panel.capsuleView.indicatorView.configure(for: state)
            let color = accentColor ?? state.accentColor
            let targetH = self.panel.capsuleView.setBreadcrumb(badge: badge, detail: detail, accentColor: color)
            let targetW = HUDCapsuleView.expandedWidth

            self.resizeIsland(toWidth: targetW, height: targetH, animated: true)

            if !self.isVisible {
                self.show(state: state)
                _ = self.panel.capsuleView.setBreadcrumb(badge: badge, detail: detail, accentColor: color)
                self.resizeIsland(toWidth: targetW, height: targetH, animated: false)
            }
        }
    }

    /// Update HUD state dynamically (e.g. listening -> thinking -> speaking).
    public func update(state: HUDState) {
        ensureMainThread {
            self.currentState = state
            let notchInfo = NotchManager.shared.currentNotch()

            if let text = self.transcribedText, !text.isEmpty {
                self.panel.capsuleView.indicatorView.configure(for: state)
                let targetH = self.panel.capsuleView.setTranscribedText(text, persona: "Donna")
                self.resizeIsland(toWidth: HUDCapsuleView.expandedWidth, height: targetH, animated: false)
            } else {
                self.panel.capsuleView.update(state: state)
                let targetH = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
                self.resizeIsland(toWidth: HUDCapsuleView.capsuleWidth, height: targetH, animated: true)
            }
            if !self.isVisible {
                self.show(state: state)
            }
        }
    }

    /// Fluidly morph island width and height with Apple-grade spring physics.
    public func resizeIsland(toWidth newWidth: CGFloat, height newHeight: CGFloat, animated: Bool = true) {
        guard self.currentWidth != newWidth || self.currentHeight != newHeight else { return }
        self.currentWidth = newWidth
        self.currentHeight = newHeight

        let newFrame = computeFrame(width: newWidth, height: newHeight)

        if animated {
            if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                // Zero travel: snap to the new pose, no intermediate geometry.
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.panel.setFrame(newFrame, display: true)
                self.panel.capsuleView.layoutSubviews(forWidth: newWidth, height: newHeight)
            } else {
                // "The Blossom": width and height morph under the same spring.
                self.springGeometry(
                    fromWidth: self.panel.frame.width, fromHeight: self.panel.frame.height,
                    toWidth: newWidth, toHeight: newHeight
                )
            }
        } else {
            self.frameSpring?.cancel()
            self.frameSpring = nil
            self.panel.setFrame(newFrame, display: true)
            self.panel.capsuleView.layoutSubviews(forWidth: newWidth, height: newHeight)
        }
        self.panel.invalidateShadow()
    }

    /// Dismiss the HUD with a snappy suction retraction back into the physical notch.
    ///
    /// Captures the current `generation` before scheduling any animation. If a
    /// newer show() runs before this dismiss's animation completes, show() bumps
    /// `generation` — so this dismiss's `cleanup` sees a stale generation and
    /// becomes a no-op instead of hiding the panel out from under the newer show.
    /// `hardCut: true` is the barge/Escape path: an instant stop with zero
    /// animation. Anything else retracts under the spring.
    public func dismiss(hardCut: Bool = false, completion: (() -> Void)? = nil) {
        ensureMainThread {
            guard self.isVisible else {
                completion?()
                return
            }

            self.generation += 1
            let myGen = self.generation
            self.lifecycle = .dismissing

            let cleanup: () -> Void = {
                guard myGen == self.generation else {
                    // Superseded by a newer show()/dismiss() — do not touch state
                    // or hide a panel that a later call already took ownership of.
                    completion?()
                    return
                }
                self.panel.orderOut(nil)
                self.lifecycle = .hidden
                self.currentState = nil
                self.transcribedText = nil
                let notchInfo = NotchManager.shared.currentNotch()
                self.currentWidth = HUDCapsuleView.capsuleWidth
                self.currentHeight = notchInfo.hasNotch ? HUDCapsuleView.notchListeningHeight : HUDCapsuleView.capsuleHeight
                self.panel.capsuleView.reset()
                completion?()
            }

            if hardCut {
                // HARD CUT: a barge is a stop, not a transition. No spring, no
                // fade, no animation of any kind — the panel is gone on this turn
                // of the run loop, inside the 50ms budget by construction.
                self.frameSpring?.cancel()
                self.frameSpring = nil
                self.panel.capsuleView.layer?.removeAllAnimations()
                self.panel.capsuleView.layer?.opacity = 1.0
                self.panel.alphaValue = 1.0
                cleanup()
                return
            }

            if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion {
                // Zero travel, time kept: an 80ms crossfade in place.
                NSAnimationContext.runAnimationGroup({ context in
                    context.duration = HUDMotionTokens.reduceMotionDuration
                    self.panel.animator().alphaValue = 0.0
                }, completionHandler: {
                    cleanup()
                })
                return
            }

            let notchInfo = NotchManager.shared.currentNotch()
            // "Suction": springs back up into the physical notch as it fades.
            let retractH = notchInfo.hasNotch ? notchInfo.notchHeight : self.currentHeight
            self.springGeometry(
                fromWidth: self.panel.frame.width, fromHeight: self.panel.frame.height,
                toWidth: HUDCapsuleView.capsuleWidth, toHeight: retractH,
                fade: .fadeOut
            ) {
                cleanup()
            }
        }
    }

    /// Compute frame based on active screen notch geometry:
    /// - If hardware notch exists: anchors flush to screen.frame.maxY, centered on the notch.
    /// - If no notch: centers horizontally on visibleFrame and floats 12px below menu bar.
    public func computeFrame(width: CGFloat, height: CGFloat) -> NSRect {
        let screen = NSScreen.main ?? (NSScreen.screens.first ?? NSScreen())
        let notchInfo = NotchManager.shared.currentNotch(for: screen)

        if notchInfo.hasNotch {
            let x = notchInfo.rect.midX - (width / 2.0)
            let y = notchInfo.screenFrame.maxY - height
            return NSRect(x: x, y: y, width: width, height: height)
        } else {
            let x = notchInfo.visibleFrame.midX - (width / 2.0)
            let y = notchInfo.visibleFrame.maxY - height - 12.0
            return NSRect(x: x, y: y, width: width, height: height)
        }
    }

    private func ensureMainThread(_ block: @escaping () -> Void) {
        if Thread.isMainThread {
            block()
        } else {
            DispatchQueue.main.async(execute: block)
        }
    }

