    /// 3-cycle horizontal micro-shake feedback (±3px over 120ms) + Basso chime
    public func triggerErrorShake(completion: (() -> Void)? = nil) {
        ensureMainThread {
            guard self.isVisible else {
                completion?()
                return
            }

            self.isErrorEnvelope = true
            // error -> off, restored once the shake ends.
            let previousGlyphState = self.panel.capsuleView.archieGlyph.state
            self.panel.capsuleView.archieGlyph.state = .error
            let restoreGlyph: () -> Void = { [weak self] in self?.panel.capsuleView.archieGlyph.state = previousGlyphState }

            if let audio = self.onErrorAudio {
                audio()
            } else if !EarconEngine.isSilentModeEnv && !HUDController.isHeadless {
                NSSound(named: "Basso")?.play()
            }

            guard !NSWorkspace.shared.accessibilityDisplayShouldReduceMotion else {
                restoreGlyph()
                completion?()
                return
            }

            // N cycles of +/- amplitude, both read from tokens, decaying to rest.
            let amplitude = HUDMotionTokens.errorShakeAmplitude
            let cycles = max(1, HUDMotionTokens.errorShakeCycles)
            var values: [Double] = [0.0]
            for cycle in 0..<cycles {
                let decay = 1.0 - (Double(cycle) / Double(cycles)) * 0.35
                values.append(-amplitude * decay)
                values.append(amplitude * decay)
            }
            values.append(0.0)

            let shake = CAKeyframeAnimation(keyPath: "transform.translation.x")
            shake.duration = HUDMotionTokens.errorShakeDuration
            shake.values = values
            shake.timingFunction = CAMediaTimingFunction(name: .easeInEaseOut)
            shake.isRemovedOnCompletion = true
            self.panel.capsuleView.layer?.add(shake, forKey: "errorShake")

            DispatchQueue.main.asyncAfter(deadline: .now() + HUDMotionTokens.errorShakeDuration) {
                restoreGlyph()
                completion?()
            }
        }
    }

    /// Alias for triggerErrorShake
    public func shakeError(completion: (() -> Void)? = nil) {
        triggerErrorShake(completion: completion)
    }

